"""Builds src/content/media.generated.ts from the derived assets in public/media.

Curation is explicit: only the entries listed below are published on the site.
Every other original was reviewed on contact sheets and excluded for the reason
recorded in ASSET-INVENTORY.md. Originals are never modified.

Indices are 1-based positions in the sorted list of derived files, the same
order used during review.
"""
import glob
import json
import os

from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..")
MEDIA = os.path.join(ROOT, "public", "media")


def sorted_names(folder, ext):
    return sorted(
        os.path.basename(p)
        for p in glob.glob(os.path.join(MEDIA, folder, f"*{ext}"))
        if not p.endswith("-640.webp")
    )


def dims(path):
    with Image.open(path) as im:
        return im.size


# key: (1-based index, alt text describing only what is visible, category, shows people)
IMAGE_SLOTS = {
    "pattern-toile": (2, "Blue and white toile-style line drawing of trees and figures on ivory", "atelier", False),
    "courtyard": (4, "Courtyard terrace with arched canopies, potted palms and wicker seating", "aura", False),
    "sculpture-sea": (11, "Sculpted white figure framed by an arch, with the sea beyond", "atelier", False),
    "sign-pattern-buggy": (10, "KAMARI lettering on a blue and white patterned wall beside a vintage buggy", "atelier", False),
    "sign-wall-night": (13, "Illuminated KAMARI lettering above a blue patterned wall", "atelier", False),
    "sign-wall-glow": (16, "Glowing KAMARI sign on a blue and white patterned wall", "atelier", False),
    "bowl-wicker": (3, "Ceramic bowl of food on a wicker chair in warm light", "savour", False),
    "plate-table": (42, "Plate of food on a wooden table close to the sea", "savour", False),
    "dishes-overhead": (31, "Overhead view of shared dishes on a table", "savour", False),
    "curries-overhead": (33, "Overhead view of curries and breads set on a table", "savour", False),
    "drink-pink": (15, "Pink cocktail with a garnish on a dark table", "elixirs", False),
    "drink-bar": (18, "Two cocktails set on the edge of a sea-facing bar", "elixirs", False),
    "drink-dark": (20, "Pink cocktail in a glass on a dark surface", "elixirs", False),
    "shoreline": (34, "Sea and rocks at the shoreline in soft light", "moments", False),
}

# Videos are keyed by derived filename (stem). Reviewed clips that show identifiable
# people or on-screen promotional overlays are excluded (see ASSET-INVENTORY.md):
#   08-22 aerial (neighbouring venues), 09-05 (overlays, people), 08-21 (people),
#   10-02 (people, neighbouring-venue aerial), 10-05_2 (label overlay),
#   10-29 series (people), 09-30 series (people, overlays).
VIDEO_SLOTS = {
    "terrace-sculpture-trim": ("terrace-sculpture-trim", "Terrace with white sculptures, KAMARI signage and the sea beyond the railing", "atelier", False),
    "plating": ("kamarigoa_2026-10-07_17-30-22_4002661447602805223_80573386722", "Gloved hands plating a dish on a patterned board", "savour", False),
}


def image_entry(idx, alt, cat, people):
    full = sorted_names("img", ".webp")[idx - 1]
    small = full.replace(".webp", "-640.webp")
    w, h = dims(os.path.join(MEDIA, "img", full))
    return {
        "src": f"/media/img/{full}",
        "small": f"/media/img/{small}",
        "width": w, "height": h, "alt": alt, "category": cat,
        "containsPeople": people, "source": f"Instagram @kamarigoa ({full})",
    }


def video_entry(stem, alt, cat, people):
    name = f"{stem}.mp4"
    poster = f"{stem}.jpg"
    w, h = dims(os.path.join(MEDIA, "poster", poster))
    return {
        "src": f"/media/video/{name}", "poster": f"/media/poster/{poster}",
        "width": w, "height": h, "alt": alt, "category": cat,
        "containsPeople": people, "source": f"Instagram @kamarigoa ({name})",
    }


images = {k: image_entry(*v) for k, v in IMAGE_SLOTS.items()}
videos = {k: video_entry(*v) for k, v in VIDEO_SLOTS.items()}

# Remove derived files that are not published, so they are not deployed.
keep_images = {v["src"].split("/")[-1] for v in images.values()} | {v["small"].split("/")[-1] for v in images.values()}
keep_videos = {f"{v[0]}.mp4" for v in VIDEO_SLOTS.values()}
keep_posters = {f"{v[0]}.jpg" for v in VIDEO_SLOTS.values()}
for folder, keep in (("img", keep_images), ("video", keep_videos), ("poster", keep_posters)):
    for path in glob.glob(os.path.join(MEDIA, folder, "*")):
        if os.path.basename(path) not in keep:
            os.remove(path)

body = (
    "// AUTO-GENERATED by scripts/gen-media-manifest.py. Do not edit by hand.\n"
    "// Publication rights: every entry is pending authorization (see ASSET-INVENTORY.md).\n"
    "export interface MediaBase { width: number; height: number; alt: string; category: string; containsPeople: boolean; source: string; }\n"
    "export interface ImageAsset extends MediaBase { src: string; small: string; }\n"
    "export interface VideoAsset extends MediaBase { src: string; poster: string; }\n"
    f"export const images = {json.dumps(images, indent=2)} as const satisfies Record<string, ImageAsset>;\n"
    f"export const videos = {json.dumps(videos, indent=2)} as const satisfies Record<string, VideoAsset>;\n"
)
with open(os.path.join(ROOT, "src", "content", "media.generated.ts"), "w") as f:
    f.write(body)
print(f"wrote {len(images)} images and {len(videos)} videos")
